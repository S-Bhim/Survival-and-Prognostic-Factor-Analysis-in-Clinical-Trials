fig('cox_forest',function(){
  z <- tidy_cox(cox); n <- nrow(z); par(mar=c(4.5,11,2,1))
  plot(z$HR,rev(seq_len(n)),log='x',xlim=range(c(z$lower,z$upper)),ylim=c(.5,n+.5),yaxt='n',xlab='Adjusted hazard ratio (95% CI)',ylab='',pch=19,col=cols[2])
  segments(z$lower,rev(seq_len(n)),z$upper,rev(seq_len(n)),col=cols[2]);axis(2,at=rev(seq_len(n)),labels=z$term,las=1,cex.axis=.8);abline(v=1,lty=2,col='gray50')
},height=7)
mart <- residuals(cox,type='martingale')
fig('martingale',function(){par(mfrow=c(1,2));for(v in c('age','lognodes')) {plot(cc[[v]],mart,pch=16,col=adjustcolor(cols[2],.35),xlab=v,ylab='Martingale residual');lines(lowess(cc[[v]],mart),col=cols[3],lwd=2)}},width=9)
dfb <- residuals(cox,type='dfbetas')
